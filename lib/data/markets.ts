/**
 * Demo catalogue.
 *
 * Everything here is deterministic: a fixed clock plus a seeded PRNG, so the
 * server and the client always render identical values. When the Postgres
 * layer lands this module is replaced by queries — nothing else changes,
 * because the rest of the app only talks to `lib/data/server-api.ts`.
 */

const HOUR = 3_600_000
const DAY = 24 * HOUR

function mulberry32(seed: number) {
  let a = seed
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

