function buildHistory(seed: Seed): PricePoint[] {
  const rand = mulberry32(
    [...seed.id].reduce((acc, ch) => (acc * 31 + ch.charCodeAt(0)) % 2_147_483_647, 7),
  )
  const points: PricePoint[] = []
  const span = 24
  const end = seed.status === 'resolved' ? DEMO_NOW - 48 * HOUR : DEMO_NOW
  const start = seed.prev
  const finish = seed.status === 'resolved' ? seed.prev : seed.price
  for (let i = 0; i <= span; i++) {
    const progress = i / span
    const drift = start + (finish - start) * progress
    const noise = (rand() - 0.5) * 70 * (1 - Math.abs(progress - 0.5))
    const value = Math.min(970, Math.max(30, Math.round(drift + noise)))
    points.push({ t: end - (span - i) * HOUR, yes: i === span ? finish : value })
  }
  return points
}

function build(seed: Seed): Market {
  const noPrice = SETTLEMENT_PAISE - seed.price
  const status: MarketStatus = seed.status ?? (seed.closesIn <= 0 ? 'closed' : 'open')
  const closesAt = DEMO_NOW + seed.closesIn * HOUR
  const outcomes = [
    {
      id: `${seed.id}:yes`,
      marketId: seed.id,
      name: seed.yes,
      side: 'yes' as const,
      pricePaise: seed.price,
      previousPricePaise: seed.prev,
    },
    {
      id: `${seed.id}:no`,
      marketId: seed.id,
      name: seed.no,
      side: 'no' as const,
      pricePaise: noPrice,
      previousPricePaise: SETTLEMENT_PAISE - seed.prev,
    },
  ]
  return {
    id: seed.id,
    slug: seed.id,
    question: seed.q,
    headline: seed.headline,
    description: seed.desc,
    resolutionCriteria: seed.criteria,
    source: seed.source,
    categoryId: seed.cat,
    kind: seed.kind,
    status,
    league: seed.league,
    emblem: seed.emblem,
    live: Boolean(seed.live) && status === 'open',
    featured: Boolean(seed.featured),
    bonus: Boolean(seed.bonus),
    createdAt: DEMO_NOW - seed.createdDaysAgo * DAY,
    opensAt: DEMO_NOW - seed.createdDaysAgo * DAY,
    closesAt,
    resolvesAt: closesAt + 2 * HOUR,
    resolvedOutcomeId:
      seed.winner ? `${seed.id}:${seed.winner}` : undefined,
    volumePaise: seed.vol * 100,
    liquidityPaise: Math.round(seed.vol * 100 * 0.18),
    traders: seed.traders,
    outcomes,
    priceHistory: buildHistory(seed),
  }
}

export const demoMarkets: Market[] = seeds.map(build)
